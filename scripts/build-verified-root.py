#!/usr/bin/env python3
"""Build the VerifiedRoot crypto and the board's policy table for the kernel link.

NativeUfs authenticates every root window against an owner-signed policy bundle.
Three things are needed to link that code:

  * `vr_open`, `vr_verify_block` and `vr_xnu_crypto` -- the real implementation,
    from kits/VerifiedRoot. Nothing here substitutes for it.
  * `verified_root_policies` and `verified_root_policy_count` -- the signed
    policies for this board, declared by drivers/VirtioMmioBlock/VerifiedBlockPolicy.h.
  * `verified_root_key` -- the trusted key, supplied independently of the
    untrusted envelope.

Only the second and third are board data, and this board does not have them yet.
They are signed over the exact root windows of the OS image that gets flashed,
so they cannot be derived offline and cannot be borrowed from another device.

So the table is generated empty. That is a truthful statement -- no policies are
configured -- not a stub that pretends to verify anything:
`NativeUfsBlock::configureVerification` rejects a zero policy count before it
reads the key or calls `vr_open`, so the driver runs with root verification
disabled and says so through gRootDiagnostic.stage. Replace the generated table
with the real bundle once one exists; nothing else has to change.

`boot_progress_poll` is defined here too. NativeUfs declares it weak and calls
it only from inside the verification path, so an observer that observes nothing
is the correct definition until a board diagnostic supplies a real one.

The result is a standalone archive. `[kernel]` builds it before the link and
`CONFIG_XNU_EXTRA_LD_ARCHIVES` puts it on the link line, where ld64 pulls the
member in to satisfy the driver's unresolved references.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/verified-root'
ARCHIVE = OUT / 'libVerifiedRoot.a'
RECIPE = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/osfmk/DEVELOPMENT/prng_random.o.json'

POLICY_SOURCE = '''/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/* Generated by build-verified-root.py: this board has no signed policy bundle.
 * verified_root_policy_count == 0 makes NativeUfsBlock::configureVerification
 * return before it reads the key or calls vr_open, so root verification is
 * disabled rather than approximated. */
#include "verified_root.h"
#include "VerifiedBlockPolicy.h"

/* extern is required here: this compiles as C++, where a namespace-scope const
 * has internal linkage without it, and NativeUfs references the key by name. */
extern const uint8_t verified_root_key[VR_KEY_BYTES] = {0};

const NativeVerifiedBlockPolicy verified_root_policies[1] = {
    {nullptr, 0},
};

const uint64_t verified_root_policy_count = 0;
'''

BOOT_PROGRESS_SOURCE = '''/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/* Generated by build-verified-root.py. NativeUfs declares this weak and calls
 * it only while verifying a root window; an observer that observes nothing is
 * the right definition until a board diagnostic supplies a real one. */
void boot_progress_poll (void)
{
}
'''


def fail(message: str) -> None:
    raise SystemExit('build-verified-root: ' + message)


def compile_environment(tree: Path) -> dict[str, str]:
    """The environment kernel.py gives the archive builders, so the clang shim resolves."""
    import os
    import platform
    if platform.system() != 'Linux':
        return dict(os.environ)
    toolchain = Path(os.environ.get('UNIXNU_TOOLCHAIN', '/opt/unixnu-linux'))
    clt = toolchain / 'CommandLineTools/usr'
    xctoolchain = toolchain / 'XcodeDefault.xctoolchain/usr'
    fakeroot = tree / '.cache/fakeroot'
    env = dict(os.environ)
    env.update({
        'PATH': os.pathsep.join([str(clt / 'bin'), str(toolchain / 'bin'), os.environ.get('PATH', '')]),
        'LC_ALL': 'C',
        'CLT_PREFIX': str(clt),
        'XCTOOLCHAIN_PREFIX': str(xctoolchain),
        'XNU_TOOLCHAIN_BIN': f'{clt / "bin"} {xctoolchain / "bin"}',
        'UNIXNU_SDKROOT': str(fakeroot),
        'UNIXNU_SDK_VERSION': '17.0',
        'UNIXNU_PLATFORM_PATH': str(fakeroot / 'Platforms/iPhoneOS.platform'),
        'CROSS_CLANG': str(toolchain / 'llvm/bin/clang'),
        'DARWIN_TRIPLE': 'arm64-apple-ios17.0',
        'CROSS_EXTRA_FLAGS': '-mllvm -disable-atexit-based-global-dtor-lowering',
        'CCC_OVERRIDE_OPTIONS': '# +-Wno-missing-designated-field-initializers +-Wno-unused-but-set-global',
    })
    return env


def command_for(record: dict, source: Path, destination: Path, includes: list[Path]) -> list[str]:
    """The kernel's own compile flags, with the input and output swapped in."""
    command, index = [], 0
    arguments = record['arguments']
    while index < len(arguments):
        value = arguments[index]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(destination)]
            index += 1
        elif value == '-Xclang' and index + 1 < len(arguments) and arguments[index + 1].startswith('-W'):
            index += 1
        elif not value.startswith('-W'):
            command.append(value)
        index += 1
    if '-o' not in command:
        command += ['-o', str(destination)]
    for include in includes:
        command += ['-I', str(include)]
    command += ['-Wno-error']
    return command


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('sources', nargs='*',
                        help='ignored; kept so board.toml entries stay uniform')
    parser.add_argument('--archive', type=Path, default=ARCHIVE, help='archive to write')
    args = parser.parse_args()
    del args.sources

    if not RECIPE.is_file():
        fail(f'missing {RECIPE}; run "unixnu build kernel" once to record the compiles')
    record = json.loads(RECIPE.read_text().strip().rstrip(','))
    OUT.mkdir(parents=True, exist_ok=True)

    includes = [ROOT / 'kits/VerifiedRoot/include',
                ROOT / 'drivers/VirtioMmioBlock',
                ROOT / '.cache/xnu-work/osfmk']
    kit = ROOT / 'kits/VerifiedRoot'
    # VerifiedBlockPolicy.h is a C++ header -- it uses extern "C", static_assert
    # and nullptr -- so the generated table is C++ even though it defines
    # C-linkage objects.
    generated = OUT / 'verified-root-policies.cpp'
    generated.write_text(POLICY_SOURCE)
    boot = OUT / 'boot-progress-stub.c'
    boot.write_text(BOOT_PROGRESS_SOURCE)

    objects = []
    for source in (kit / 'src/verified_root.c', kit / 'adapters/xnu_crypto.c', generated, boot):
        if not source.is_file():
            fail(f'missing {source}')
        destination = OUT / (source.stem + '.o')
        command = command_for(record, source, destination, includes)
        (OUT / f'{source.stem}.compile-command.json').write_text(json.dumps(command, indent=2) + '\n')
        result = subprocess.run(command, cwd=record['directory'], env=compile_environment(ROOT),
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        (OUT / f'{source.stem}.compile.log').write_text(result.stdout or '')
        if result.returncode:
            fail(f'{source.name} did not compile:\n' + (result.stdout or '')[-3000:])
        objects.append(destination)

    args.archive.parent.mkdir(parents=True, exist_ok=True)
    args.archive.unlink(missing_ok=True)
    result = subprocess.run(['xcrun', 'ar', 'rcs', str(args.archive), *map(str, objects)],
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if result.returncode:
        fail('xcrun ar failed: ' + (result.stdout or ''))

    # cctools nm has no --defined-only, so list everything and drop the
    # undefined rows: "                 U _name" against "0000000000000000 T _name".
    listing = subprocess.run(['xcrun', 'nm', '-g', str(args.archive)],
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    (OUT / 'nm.txt').write_text(listing.stdout or '')
    defined = {parts[2] for line in (listing.stdout or '').splitlines()
               if len(parts := line.split()) == 3 and parts[1] != 'U'}
    needed = {'_vr_open', '_vr_verify_block', '_vr_xnu_crypto',
              '_verified_root_key', '_verified_root_policies', '_verified_root_policy_count',
              '_boot_progress_poll'}
    missing = sorted(needed - defined)
    if missing:
        fail('these symbols are still missing from the archive: ' + ', '.join(missing))

    (OUT / 'report.json').write_text(json.dumps({
        'sources': ['kits/VerifiedRoot/src/verified_root.c', 'kits/VerifiedRoot/adapters/xnu_crypto.c',
                    'generated verified-root-policies.cpp', 'generated boot-progress-stub.c'],
        'verified_root_policy_count': 0,
        'root_verification': 'disabled: this board has no signed policy bundle',
        'boot_progress_poll': 'no-op observer',
        'archive': str(args.archive),
        'original_code_modified': False,
    }, indent=2) + '\n')
    print('PASS: real VerifiedRoot crypto + empty policy table -> ' + args.archive.name)
    print('      root verification is disabled: no signed policy bundle exists for this board')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
